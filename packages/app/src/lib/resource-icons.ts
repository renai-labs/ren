export type Face =
  | { readonly type: "image"; readonly url: string }
  | { readonly type: "tile"; readonly Icon: Icon; readonly className: string }
  | { readonly type: "emoji"; readonly emoji: string }

export const faceOf = (icon: string | null | undefined): Face | undefined => {
  const value = ResourceIcon.parse(icon)
  if (value?.type !== "tabler") return value
  const glyph = find(value.name)
  return glyph && { type: "tile", Icon: glyph.Icon, className: tiles[value.color] }
}
