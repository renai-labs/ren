export * as EmitEffectImported from "./emit-effect-imported.js"

import { ClientTree } from "./client-tree.js"
import { Errors } from "./errors.js"
import { Names } from "./names.js"
import { Operations } from "./operations.js"
import { SchemaShape } from "./schema-shape.js"
import type { Types } from "./types.js"

export type Options = { readonly module: string; readonly api: string }

const clientErrorFile = {
  path: "client-error.ts",
  content:
    'import { Schema } from "effect"\n\nexport class ClientError extends Schema.TaggedError<ClientError>()("ClientError", {\n  cause: Schema.Defect(),\n}) {}\n',
}

const indexFile = {
  path: "index.ts",
  content: `export { ClientError } from "./client-error.js"\n${Names.clientNamespaceExport}`,
}

function renderInputType(item: Types.Endpoint, prefix: string) {
  return item.input
    .map(
      (field) =>
        `readonly ${JSON.stringify(field.name)}${field.optional ? "?" : ""}: ${prefix}Request[${JSON.stringify(field.source)}]${SchemaShape.isOpaquePayload(item) && field.source === "payload" ? "" : `[${JSON.stringify(field.name)}]`}`,
    )
    .join("; ")
}

function renderRequest(item: Types.Endpoint) {
  const access = (name: string) =>
    `input${item.operation.inputMode === "optional" ? "?." : ""}[${JSON.stringify(name)}]`
  const schemas = { params: item.params, query: item.query, headers: item.headers, payload: item.payloads[0] }
  return (["params", "query", "headers", "payload"] as const)
    .flatMap((source) => {
      const fields = item.input.filter((field) => field.source === source)
      const first = fields[0]
      if (first === undefined) return schemas[source] === undefined ? [] : [`${source}: { }`]
      if (SchemaShape.isOpaquePayload(item) && source === "payload") return [`${source}: ${access(first.name)}`]
      return [
        `${source}: { ${fields.map((field) => `${JSON.stringify(field.name)}: ${access(field.name)}`).join(", ")} }`,
      ]
    })
    .join(", ")
}

function renderEndpointAdapter(group: Types.Group, item: Types.Endpoint, rawGroup: string) {
  const prefix = Names.endpointTypeName(group, item)
  const inputMode = item.operation.inputMode
  const identifier = JSON.stringify(item.endpoint.identifier)
  const argument = inputMode === "none" ? "" : `input${inputMode === "optional" ? "?" : ""}: ${prefix}Input`
  // oxlint-disable-next-line ren/no-comments -- HttpApiClient distributes union payloads into union request objects while the flattened input holds one object with a union value; TypeScript cannot correlate the equivalent shapes.
  const rawCall = `raw[${identifier}]({ ${renderRequest(item)} }${SchemaShape.isOpaquePayload(item) ? ` as ${prefix}Request` : ""})`
  const result =
    item.operation.success === "stream"
      ? `Stream.unwrap(${rawCall}.pipe(Effect.mapError(mapClientError), Effect.map((stream) => stream.pipe(Stream.mapError(mapClientError)))))`
      : `${rawCall}.pipe(Effect.mapError(mapClientError)${item.unwrapData ? ", Effect.map((value) => value.data)" : ""})`
  const declarations =
    inputMode === "none"
      ? ""
      : `type ${prefix}Request = Parameters<${rawGroup}[${identifier}]>[0]\ntype ${prefix}Input = { ${renderInputType(item, prefix)} }\n`
  return `${declarations}const ${Names.endpointAdapterName(group, item)} = (raw: ${rawGroup}) => (${argument}) => ${result}`
}

function renderGroupAdapter(group: Types.Group) {
  const rawGroup = group.endpoints[0]?.topLevel ? "RawClient" : `RawClient[${JSON.stringify(group.identifier)}]`
  const methods = group.endpoints.map((item) => renderEndpointAdapter(group, item, rawGroup))
  const fields = ClientTree.renderClientTree(
    group.endpoints,
    (item) => `${Names.endpointAdapterName(group, item)}(raw)`,
    (name, value) => `${JSON.stringify(name)}: ${value}`,
    ", ",
  )
  return `${methods.join("\n\n")}\n\nconst adaptGroup${Names.groupTypeName(group)} = (raw: ${rawGroup}) => ({ ${fields} })`
}

export function emitEffectImported(contract: Types.Contract, options: Options): Types.Output {
  const groups = contract.groups
  const api = options.api
  const collides = groups.some((group) =>
    group.endpoints.some((endpoint) => Names.endpointAdapterName(group, endpoint) === api),
  )
  if (collides) {
    throw new Errors.GenerationError({ reason: `Generated Effect adapter collides with imported endpoint: ${api}` })
  }
  const fields = groups.map((group) =>
    group.endpoints[0]?.topLevel
      ? `...adaptGroup${Names.groupTypeName(group)}(raw)`
      : `${JSON.stringify(group.identifier)}: adaptGroup${Names.groupTypeName(group)}(raw[${JSON.stringify(group.identifier)}])`,
  )
  const usesStream = groups.some((group) => group.endpoints.some((item) => item.operation.success === "stream"))
  const client = `// Generated by @ren/httpapi-codegen. Do not edit.\nimport { Effect${usesStream ? ", Stream" : ""}, Schema } from "effect"\nimport { Sse } from "effect/encoding"\nimport { HttpClientError } from "effect/http"\nimport { HttpApiClient } from "effect/http-api"\nimport { ${api} } from ${JSON.stringify(options.module)}\nimport { ClientError } from "./client-error.js"\n\ntype RawClient = HttpApiClient.ForApi<typeof ${api}>\n\nconst mapClientError = <E>(error: E) => HttpClientError.isHttpClientError(error) || Schema.isSchemaError(error) || Sse.Retry.is(error) ? new ClientError({ cause: error }) : error\n\n${groups.map(renderGroupAdapter).join("\n\n")}\n\nconst adaptClient = (raw: RawClient) => ({ ${fields.join(", ")} })\n\nexport const make = (options?: { readonly baseUrl?: URL | string }) => HttpApiClient.make(${api}, options).pipe(Effect.map(adaptClient))\n`
  return {
    operations: Operations.operations(groups),
    files: [clientErrorFile, { path: "client.ts", content: client }, indexFile],
  }
}
