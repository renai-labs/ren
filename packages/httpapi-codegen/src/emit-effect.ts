export * as EmitEffect from "./emit-effect.js"

import { Errors } from "./errors.js"
import { Names } from "./names.js"
import { Operations } from "./operations.js"
import { RenderGroup } from "./render-group.js"
import type { Types } from "./types.js"

export const clientErrorFile = {
  path: "client-error.ts",
  content:
    'import { Schema } from "effect"\n\nexport class ClientError extends Schema.TaggedError<ClientError>()("ClientError", {\n  cause: Schema.Defect(),\n}) {}\n',
}

export const indexFile = {
  path: "index.ts",
  content: `export { ClientError } from "./client-error.js"\n${Names.clientNamespaceExport}`,
}

function renderClient(groups: ReadonlyArray<Types.Group>) {
  const imports = groups
    .map(
      (group) =>
        `import { adaptGroup${Names.groupTypeName(group)}, Group${Names.groupTypeName(group)} } from ${JSON.stringify(`./${group.module}`)}`,
    )
    .join("\n")
  const api = `HttpApi.make("generated")${groups.map((group) => `.add(Group${Names.groupTypeName(group)})`).join("")}`
  const fields = groups.flatMap((group) => {
    if (!group.endpoints[0]?.topLevel) {
      return [
        `${JSON.stringify(group.identifier)}: adaptGroup${Names.groupTypeName(group)}(raw[${JSON.stringify(group.identifier)}])`,
      ]
    }
    const raw = `{ ${group.endpoints.map((item) => `${JSON.stringify(item.endpoint.identifier)}: raw[${JSON.stringify(item.endpoint.identifier)}]`).join(", ")} }`
    return [`...adaptGroup${Names.groupTypeName(group)}(${raw})`]
  })
  return `// Generated by @ren/httpapi-codegen. Do not edit.\nimport { Effect } from "effect"\nimport { HttpApi, HttpApiClient } from "effect/http-api"\n${imports}\n\nconst Api = ${api}\nconst adaptClient = (raw: HttpApiClient.ForApi<typeof Api>) => ({ ${fields.join(", ")} })\n\nexport const make = (options?: { readonly baseUrl?: URL | string }) =>\n  HttpApiClient.make(Api, options).pipe(Effect.map(adaptClient))\n`
}

export function emitEffect(contract: Types.Contract): Types.Output {
  const endpoint = contract.groups.flatMap((group) => group.endpoints).find((item) => !item.effectPortable)
  if (endpoint !== undefined) {
    throw new Errors.GenerationError({
      reason: `Effect schema requires authoritative import: ${endpoint.group}.${endpoint.endpoint.identifier}`,
    })
  }
  return {
    operations: Operations.operations(contract.groups),
    files: [
      ...contract.groups.map((group) => ({ path: `${group.module}.ts`, content: RenderGroup.renderGroup(group) })),
      clientErrorFile,
      { path: "client.ts", content: renderClient(contract.groups) },
      indexFile,
    ],
  }
}
